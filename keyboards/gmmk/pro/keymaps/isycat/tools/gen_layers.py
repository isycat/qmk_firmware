"""Write layers.h: the built-in keymap as a raw 11x8 matrix, valid for ANSI and ISO.

Usage: python3 tools/gen_layers.py   (run from this keymap folder)
Keys are listed in the ANSI LAYOUT order of keyboards/gmmk/pro/rev1/ansi/keyboard.json,
then the two ISO-only keys. VIA overrides all of this once you edit the keymap there.
"""
import json, os

here = os.path.dirname(os.path.abspath(__file__))
root = os.path.join(here, '..', '..', '..')
ansi = [tuple(k['matrix']) for k in json.load(open(os.path.join(root, 'rev1/ansi/keyboard.json')))['layouts']['LAYOUT']['layout']]
ISO_EXTRA = [(8, 4), (2, 3)]  # ISO key left of Enter (NUHS), ISO key right of left Shift (NUBS)

_ = 'KC_TRNS'
LAYERS = [
    # 0: base
    '''KC_ESC KC_F1 KC_F2 KC_F3 KC_F4 KC_F5 KC_F6 KC_F7 KC_F8 KC_F9 KC_F10 KC_F11 KC_F12 KC_PSCR KC_MUTE
    KC_GRV KC_1 KC_2 KC_3 KC_4 KC_5 KC_6 KC_7 KC_8 KC_9 KC_0 KC_MINS KC_EQL KC_BSPC KC_DEL
    KC_TAB KC_Q KC_W KC_E KC_R KC_T KC_Y KC_U KC_I KC_O KC_P KC_LBRC KC_RBRC KC_BSLS KC_PGUP
    KC_F24 KC_A KC_S KC_D KC_F KC_G KC_H KC_J KC_K KC_L KC_SCLN KC_QUOT KC_ENT KC_PGDN
    KC_LSFT KC_Z KC_X KC_C KC_V KC_B KC_N KC_M KC_COMM KC_DOT KC_SLSH KC_RSFT KC_UP KC_END
    KC_LCTL CK_TH1 KC_LALT KC_SPC CK_SWALT MO(1) KC_RCTL KC_LEFT KC_DOWN KC_RGHT
    KC_NUHS KC_NUBS''',
    # 1: Fn
    '''_ _ _ _ _ _ _ _ _ _ _ _ _ KC_SCRL CK_PPTD
    _ _ _ _ _ _ _ _ _ _ _ _ _ _ KC_INS
    _ RGB_SPD RGB_VAI RGB_SPI RGB_HUI RGB_SAI _ _ _ _ _ _ _ QK_BOOT KC_HOME
    _ RGB_RMOD RGB_VAD RGB_MOD RGB_HUD RGB_SAD _ _ _ _ _ _ _ _
    _ RGB_TOG _ _ _ _ NK_TOGG _ _ _ _ _ _ _
    _ _ _ _ _ _ _ _ _ _
    _ _''',
    None,
    None,
]
ENCODERS = [('KC_VOLD', 'KC_VOLU'), ('KC_MPRV', 'KC_MNXT'), (_, _), (_, _)]

positions = ansi + ISO_EXTRA
out = ['// Generated by tools/gen_layers.py. Edit the keymap in VIA, not here.',
       '// Raw matrix order: 11 rows x 8 cols, shared by ANSI and ISO boards.',
       'const uint16_t PROGMEM keymaps[][MATRIX_ROWS][MATRIX_COLS] = {']
for n, spec in enumerate(LAYERS):
    grid = [['KC_NO'] * 8 for _ in range(11)]
    keys = spec.split() if spec else [_] * len(positions)
    keys = [_ if k == '_' else k for k in keys]
    assert len(keys) == len(positions), (n, len(keys), len(positions))
    for (r, c), k in zip(positions, keys):
        grid[r][c] = k
    out.append(f'    [{n}] = {{')
    for row in grid:
        out.append('        { ' + ', '.join(f'{k:>9}' for k in row) + ' },')
    out.append('    },')
out.append('};')
out.append('')
out.append('#if defined(ENCODER_MAP_ENABLE)')
out.append('const uint16_t PROGMEM encoder_map[][NUM_ENCODERS][NUM_DIRECTIONS] = {')
for n, (ccw, cw) in enumerate(ENCODERS):
    out.append(f'    [{n}] = {{ ENCODER_CCW_CW({ccw}, {cw}) }},')
out.append('};')
out.append('#endif')
open(os.path.join(here, '..', 'layers.h'), 'w').write('\n'.join(out) + '\n')
